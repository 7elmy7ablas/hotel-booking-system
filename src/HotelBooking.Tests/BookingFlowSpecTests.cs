    #region US5: Delete Booking (FR-008) - Admin Only

    /// <summary>
    /// US5-AC1: Admin can soft-delete a booking
    /// </summary>
    [Fact]
    public async Task DeleteBooking_ShouldSoftDelete_WhenCalledByAdmin()
    {
        // Arrange
        var admin = await CreateTestUser("Admin");
        var hotel = await CreateTestHotel();
        var room = await CreateTestRoom(hotel.Id);
        var booking = await CreateTestBooking(admin.Id, room.Id,
            DateTime.UtcNow.Date.AddDays(10), DateTime.UtcNow.Date.AddDays(12));

        SetupUserClaims(admin.Id, "Admin");

        // Act
        var result = await _controller.DeleteBooking(booking.Id);

        // Assert
        result.Should().BeOfType<NoContentResult>();

        var deletedBooking = await _context.Bookings
            .IgnoreQueryFilters()
            .FirstOrDefaultAsync(b => b.Id == booking.Id);

        deletedBooking.Should().NotBeNull();
        deletedBooking!.IsDeleted.Should().BeTrue();
    }

    /// <summary>
    /// US5-AC2: Deleted booking's room becomes available for new bookings
    /// </summary>
    [Fact]
    public async Task DeleteBooking_ShouldFreeRoom_ForNewBookings()
    {
        // Arrange
        var admin = await CreateTestUser("Admin");
        var hotel = await CreateTestHotel();
        var room = await CreateTestRoom(hotel.Id);
        
        var checkIn = DateTime.UtcNow.Date.AddDays(10);
        var checkOut = checkIn.AddDays(3);
        var booking = await CreateTestBooking(admin.Id, room.Id, checkIn, checkOut);

        SetupUserClaims(admin.Id, "Admin");

        // Delete the booking
        await _controller.DeleteBooking(booking.Id);

        // Act - Try to book the same dates
        var newBooking = CreateBookingEntity(admin.Id, room.Id, checkIn, checkOut);
        var result = await _controller.CreateBooking(newBooking);

        // Assert - New booking should succeed
        result.Should().BeOfType<CreatedAtActionResult>();
    }

