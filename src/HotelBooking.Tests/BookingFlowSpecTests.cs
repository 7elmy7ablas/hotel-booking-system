public class BookingsControllerBookingFlowTests : IDisposable
{
    private readonly ApplicationDbContext _context;
    private readonly Mock<ILogger<BookingsController>> _mockLogger;
    private readonly Mock<IRepository<Booking>> _mockBookingRepository;
    private readonly Mock<ILogger<BookingValidationService>> _mockValidationLogger;
    private readonly BookingValidationService _validationService;
    private readonly BookingsController _controller;

    public BookingsControllerBookingFlowTests()
    {
        var options = new DbContextOptionsBuilder<ApplicationDbContext>()
            .UseInMemoryDatabase(databaseName: $"BookingFlowTests_{Guid.NewGuid()}")
            .Options;

        _context = new ApplicationDbContext(options);
        _mockLogger = new Mock<ILogger<BookingsController>>();
        _mockBookingRepository = new Mock<IRepository<Booking>>();
        _mockValidationLogger = new Mock<ILogger<BookingValidationService>>();

        // Default: return context bookings for validation
        _mockBookingRepository.Setup(r => r.GetAllAsync(It.IsAny<CancellationToken>()))
            .ReturnsAsync(() => _context.Bookings.ToList());

        _validationService = new BookingValidationService(_mockBookingRepository.Object, _mockValidationLogger.Object);
        _controller = new BookingsController(_context, _mockLogger.Object, _validationService);
    }

    public void Dispose()
    {
        _context.Database.EnsureDeleted();
        _context.Dispose();
    }

    /// <summary>
    /// Helper to create a Booking entity for controller tests
    /// </summary>
    private Booking CreateBookingEntity(Guid userId, Guid roomId, DateTime checkIn, DateTime checkOut)
    {
        return new Booking
        {
            Id = Guid.Empty, // Will be generated by controller
            UserId = userId,
            RoomId = roomId,
            CheckIn = checkIn,
            CheckOut = checkOut,
            TotalPrice = 0, // Will be calculated by controller
            Status = string.Empty,
            CreatedAt = DateTime.UtcNow
        };
    }

    #region Test Data Setup

    private async Task<User> CreateTestUser(string role = "User")
    {
        var user = new User
        {
            Id = Guid.NewGuid(),
            Email = $"user_{Guid.NewGuid():N}@test.com",
            PasswordHash = "hashedpassword",
            FullName = "Test User",
            Role = role,
            CreatedAt = DateTime.UtcNow
        };
        _context.Users.Add(user);
        await _context.SaveChangesAsync();
        return user;
    }

    private async Task<Hotel> CreateTestHotel(string location = "Cairo")
    {
        var hotel = new Hotel
        {
            Id = Guid.NewGuid(),
            Name = "Nile Ritz-Carlton",
            Location = location,
            Description = "Luxury hotel in downtown Cairo",
            Rating = 4.8m,
            CreatedAt = DateTime.UtcNow
        };
        _context.Hotels.Add(hotel);
        await _context.SaveChangesAsync();
        return hotel;
    }

    private async Task<Room> CreateTestRoom(Guid hotelId, decimal pricePerNight = 150m, int capacity = 2)
    {
        var room = new Room
        {
            Id = Guid.NewGuid(),
            HotelId = hotelId,
            RoomType = "Deluxe Suite",
            PricePerNight = pricePerNight,
            Capacity = capacity,
            IsAvailable = true,
            CreatedAt = DateTime.UtcNow
        };
        _context.Rooms.Add(room);
        await _context.SaveChangesAsync();
        return room;
    }

    private async Task<Booking> CreateTestBooking(Guid userId, Guid roomId, DateTime checkIn, DateTime checkOut, string status = "Confirmed")
    {
        var room = await _context.Rooms.FindAsync(roomId);
        var nights = (checkOut - checkIn).Days;
        var totalPrice = (room?.PricePerNight ?? 100m) * nights;

        var booking = new Booking
        {
            Id = Guid.NewGuid(),
            UserId = userId,
            RoomId = roomId,
            CheckIn = checkIn,
            CheckOut = checkOut,
            TotalPrice = totalPrice,
            Status = status,
            CreatedAt = DateTime.UtcNow
        };
        _context.Bookings.Add(booking);
        await _context.SaveChangesAsync();
        return booking;
    }

    private void SetupUserClaims(Guid userId, string role = "User")
    {
        var claims = new List<Claim>
        {
            new Claim("userId", userId.ToString()),
            new Claim(ClaimTypes.Role, role)
        };
        var identity = new ClaimsIdentity(claims, "TestAuth");
        var claimsPrincipal = new ClaimsPrincipal(identity);
        _controller.ControllerContext = new ControllerContext
        {
            HttpContext = new DefaultHttpContext { User = claimsPrincipal }
        };
    }

    #endregion

    #region US3: Create Booking with Price Calculation (FR-003)

    /// <summary>
    /// US3-AC1: Given user selects Room ($150/night), When booking Feb 15-18,
    /// Then TotalPrice = 3 × $150 = $450
    /// </summary>
    [Fact]
    public async Task CreateBooking_ShouldCalculateCorrectTotalPrice_ForThreeNights()
    {
        // Arrange
        var user = await CreateTestUser();
        var hotel = await CreateTestHotel();
        var room = await CreateTestRoom(hotel.Id, pricePerNight: 150m);
        SetupUserClaims(user.Id);

        var checkIn = DateTime.UtcNow.Date.AddDays(15);
        var checkOut = checkIn.AddDays(3); // 3 nights

        var booking = CreateBookingEntity(user.Id, room.Id, checkIn, checkOut);

        // Act
        var result = await _controller.CreateBooking(booking);

        // Assert
        var createdResult = result.Should().BeOfType<CreatedAtActionResult>().Subject;
        createdResult.StatusCode.Should().Be(201);

        var createdBooking = createdResult.Value as Booking;
        createdBooking!.TotalPrice.Should().Be(450m); // 3 nights × $150
    }

    /// <summary>
    /// US3-AC2: Server MUST recalculate TotalPrice regardless of client-provided value
    /// </summary>
    [Fact]
    public async Task CreateBooking_ShouldIgnoreClientTotalPrice_AndRecalculateServerSide()
    {
        // Arrange
        var user = await CreateTestUser();
        var hotel = await CreateTestHotel();
        var room = await CreateTestRoom(hotel.Id, pricePerNight: 100m);
        SetupUserClaims(user.Id);

        var checkIn = DateTime.UtcNow.Date.AddDays(5);
        var checkOut = checkIn.AddDays(2); // 2 nights = $200

        var booking = CreateBookingEntity(user.Id, room.Id, checkIn, checkOut);
        booking.TotalPrice = 9999m; // Client tries to set wrong price

        // Act
        var result = await _controller.CreateBooking(booking);

        // Assert
        var createdResult = result.Should().BeOfType<CreatedAtActionResult>().Subject;
        var createdBooking = createdResult.Value as Booking;
        createdBooking!.TotalPrice.Should().Be(200m); // Server calculates: 2 nights × $100
        createdBooking.TotalPrice.Should().NotBe(9999m);
    }

    /// <summary>
    /// US3-AC3: Successful booking returns 201 with booking details
    /// </summary>
    [Fact]
    public async Task CreateBooking_ShouldReturn201_WithBookingDetails()
    {
        // Arrange
        var user = await CreateTestUser();
        var hotel = await CreateTestHotel();
        var room = await CreateTestRoom(hotel.Id);
        SetupUserClaims(user.Id);

        var checkIn = DateTime.UtcNow.Date.AddDays(10);
        var checkOut = checkIn.AddDays(2);

        var booking = CreateBookingEntity(user.Id, room.Id, checkIn, checkOut);

        // Act
        var result = await _controller.CreateBooking(booking);

        // Assert
        var createdResult = result.Should().BeOfType<CreatedAtActionResult>().Subject;
        createdResult.StatusCode.Should().Be(201);

        var createdBooking = createdResult.Value as Booking;
        createdBooking.Should().NotBeNull();
        createdBooking!.Id.Should().NotBeEmpty();
