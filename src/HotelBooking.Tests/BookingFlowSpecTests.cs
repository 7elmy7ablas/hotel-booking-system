    #region EC-001: Overlapping Booking Attempt

    /// <summary>
    /// EC-001: Overlapping dates should return 400 Bad Request (validation error)
    /// </summary>
    [Fact]
    public async Task CreateBooking_ShouldReturnBadRequest_WhenDatesOverlap()
    {
        // Arrange - Existing: Feb 15-18
        var user = await CreateTestUser();
        var hotel = await CreateTestHotel();
        var room = await CreateTestRoom(hotel.Id);
        
        var existingCheckIn = DateTime.UtcNow.Date.AddDays(15);
        var existingCheckOut = existingCheckIn.AddDays(3);
        await CreateTestBooking(user.Id, room.Id, existingCheckIn, existingCheckOut);
        
        SetupUserClaims(user.Id);

        // New attempt: Feb 16-20 (overlaps)
        var booking = CreateBookingEntity(user.Id, room.Id, 
            existingCheckIn.AddDays(1), // Feb 16
            existingCheckOut.AddDays(2)); // Feb 20

        // Act
        var result = await _controller.CreateBooking(booking);

        // Assert
        var badRequestResult = result.Should().BeOfType<BadRequestObjectResult>().Subject;
        badRequestResult.StatusCode.Should().Be(400);
    }

    /// <summary>
    /// EC-001 Table: Sequential bookings should be allowed
    /// Existing: Feb 15-18, New: Feb 18-20
    /// </summary>
    [Fact]
    public async Task CreateBooking_ShouldSucceed_WhenBookingsAreSequential()
    {
        // Arrange
        var user = await CreateTestUser();
        var hotel = await CreateTestHotel();
        var room = await CreateTestRoom(hotel.Id);
        
        var existingCheckIn = DateTime.UtcNow.Date.AddDays(15);
        var existingCheckOut = existingCheckIn.AddDays(3); // Feb 18
        await CreateTestBooking(user.Id, room.Id, existingCheckIn, existingCheckOut);
        
        SetupUserClaims(user.Id);

        // New: starts exactly when existing ends
        var booking = CreateBookingEntity(user.Id, room.Id,
            existingCheckOut, // Feb 18
            existingCheckOut.AddDays(2)); // Feb 20

        // Act
        var result = await _controller.CreateBooking(booking);

        // Assert
        result.Should().BeOfType<CreatedAtActionResult>();
    }

